"""usage: emit_d50_waves.py <d50 512KB ic30> > src/chips/d50Waves.ts
Per-wave descriptors of the LA32 PCM ROM. Layout measured on the dump and matched with the D-50 wave list
(Terry Fryer, "Synthesizer Set-Ups: Roland D-50", p. 15: waves 1-47 attacks, 48-76 looped sounds, 77-100 combinations):
  - the ROM is 128 pages of 2048 samples; pages 0-91 hold the 47 attacks in order (a recipe fitted on each);
  - pages 92-111 are the 20 exactly repeating loops, waves 48-67 (Drawbar Organ .. Male 1): a harmonic profile each;
  - pages 112-118 are Spectrum 1-7 (waves 68-74) and page 119 is Male 2 (wave 75): lines of the 2048 sample cycle;
  - pages 120-127 are the white noise of wave 76 (spectral flatness 0.5): played as noise.
Waves 77-100 are combinations of 1-76: they have no data of their own."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from la32 import decode_la32, RATE
from attackfit import onsets, fit_attack

PAGE = 2048
x = decode_la32(sys.argv[1]).astype(np.float64)

# attacks: the onsets of pages 0-91 plus the start of the ROM; one more than the 47 waves, the weakest off-page one goes
on = [o for o in onsets(x, thr=12, step=6) if o < 92 * PAGE]
starts = [0] + on
if len(starts) == 48:
    def jump(o):
        a = np.sqrt((x[max(0, o - 256) : o] ** 2).mean()) + 1
        b = np.sqrt((x[o : o + 256] ** 2).mean()) + 1
        return 20 * np.log10(b / a)
    off_page = [o for o in on if min(o % PAGE, PAGE - o % PAGE) > 128]
    starts.remove(min(off_page, key=jump))
assert len(starts) == 47, f'expected 47 attacks, found {len(starts)}'
attacks = []
for k, a in enumerate(starts):
    b = min(starts[k + 1] if k + 1 < len(starts) else 92 * PAGE, a + 16384)
    attacks.append(fit_attack(x[a:b], RATE))

def lines_of(cycle, kmax):
    spec = np.abs(np.fft.rfft(cycle - cycle.mean()))
    ks = list(range(1, min(len(spec), kmax + 1)))
    top = sorted(sorted(ks, key=lambda k: -spec[k])[:12])
    return [[k, round(float(spec[k] / spec[top].max()), 3)] for k in top]

# looped sounds, waves 48-76: one page each (wave 76 takes the 8 last pages)
loops = []
for p in range(92, 120):
    pg = x[p * PAGE : (p + 1) * PAGE]
    m = pg - pg.mean()
    f = np.fft.rfft(m)
    cyc = np.fft.irfft(f * np.conj(f)) / ((m**2).sum() + 1e-9)
    rs = {L: cyc[L] for L in (64, 128, 256, 512, 1024)}
    top = max(rs.values())
    L = min(L for L, r in rs.items() if r >= 0.99 * top)
    loops.append(lines_of(pg[:L], 64) if top >= 0.97 else lines_of(pg, 96))
loops.append(None)  # wave 76: noise

g = lambda v: '%g' % v
print("""import type { D50Attack } from './historical.ts';

/**
 * Per-wave parametric descriptors of the D-50 PCM waves, generated by `tools/rom-analysis/emit_d50_waves.py` from
 * measurements of the user's own dump of the D-50 sample ROM, read offline. Only a few averaged numbers per wave are
 * kept: no sample, no waveform table and no ROM byte is part of the package. Do not edit by hand: regenerate.
 */

/** PCM waves 1-47, the attacks, one recipe each: partials [ratio to the pitch, amplitude, decay in s] and a noise burst */""")
print('export const D50_WAVE_ATTACKS: readonly D50Attack[] = [')
for k, a in enumerate(attacks):
    hs = ', '.join('[%s, %s, %s]' % (g(r), g(v), g(d)) for r, v, d in a['harmonics'])
    print("\t{ name: 'PCM %d', harmonics: [%s], noise: %s, noiseDecay: %s, duration: %s }," % (k + 1, hs, g(a['noise']), g(a['noiseDecay']), g(max(0.3, a['duration']))))
print('];\n')
print('/** PCM waves 48-76, the looped sounds: the strongest harmonics [number, amplitude] of the cycle; the last (wave 76, Noise) is null */')
print('export const D50_WAVE_LOOPS: readonly (readonly (readonly [number, number])[] | null)[] = [')
for l in loops:
    print('\tnull,' if l is None else '\t[' + ', '.join('[%d, %s]' % (k, g(a)) for k, a in l) + '],')
print('];')
